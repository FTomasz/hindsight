"""Builds js/content/words.js: one smoothed series per phrase, 1850-2022.

Usage: python3 tools/build-words.py tools/raw tools/phrases.txt > js/content/words.js
Values are uses per million words, centered 3-year average, 3 significant figures.
"""
import json, os, sys

START, END = 1850, 2022
raw_dir, list_file = sys.argv[1], sys.argv[2]
phrases = [l.strip() for l in open(list_file) if l.strip() and not l.startswith('#')]

def sig(v):
    return 0 if v == 0 else float(f"{v:.3g}")

out = []
for p in phrases:
    f = os.path.join(raw_dir, p.replace(' ', '_').replace('/', '_').lower() + '.json')
    d = json.load(open(f))
    assert d and d[0]['ngram'] == p, p
    ts = d[0]['timeseries']
    assert len(ts) == 223
    sm = []
    for i in range(len(ts)):
        w = ts[max(0, i - 1):i + 2]
        sm.append(sum(w) / len(w) * 1e6)
    vals = [sig(sm[y - 1800]) for y in range(START, END + 1)]
    if max(vals) < 0.05:
        print('skip (too rare):', p, file=sys.stderr)
        continue
    out.append([p, vals])

print('// Generated by tools/build-words.py from Google Books Ngram Viewer data')
print('// (English corpus, 2022 edition). Uses per million words, centered 3-year average.')
print(f'export const WORDS_START = {START};')
print(f'export const WORDS_END = {END};')
print('export const WORDS = [')
for p, v in out:
    print(' [' + json.dumps(p) + ',' + json.dumps(v, separators=(',', ':')) + '],')
print('];')
